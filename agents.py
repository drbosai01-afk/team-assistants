AGENTS: dict[str, Agent] = {a.id: a for a in (ZAKAZOVOD, MASTER, REVIEWER)}


def list_agents() -> list[Agent]:
    return [ZAKAZOVOD, MASTER, REVIEWER]


async def chat_with_agent(agent: Agent, history: list[dict], user_message: str) -> str:
    messages = history + [{"role": "user", "content": user_message}]
    return await call_llm(agent.system_prompt, messages)
